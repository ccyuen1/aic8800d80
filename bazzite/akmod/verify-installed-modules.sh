#!/usr/bin/env bash
# Verify that the active kernel has the expected AIC8800D80 akmod modules.
set -euo pipefail

usage() {
    cat <<'USAGE'
Usage: verify-installed-modules.sh [kernel-release]

Checks that the AIC8800D80 modules are installed in the selected kernel's
module tree and have matching vermagic. If a module is RPM-owned, also checks
that the owner is the matching exact-kernel kmod package. Without an argument,
checks the currently running kernel.
USAGE
}

if [[ ${1:-} == --help ]]; then
    usage
    exit 0
fi

if [[ $# -gt 1 ]]; then
    usage >&2
    exit 2
fi

if ((EUID != 0)); then
    echo 'Run this with sudo: sudo make installed-modules-verify' >&2
    exit 2
fi

kernel_release=${1:-$(uname -r)}
module_root="/usr/lib/modules/$kernel_release"
module_dir="$module_root/extra/aic8800d80"
expected_modules=(aic8800_fdrv aic_load_fw aic_zlp_quirk)

if [[ ! -d "$module_root" ]]; then
    printf 'Kernel module directory does not exist: %s\n' "$module_root" >&2
    exit 3
fi

if [[ ! -d "$module_dir" ]]; then
    printf 'AIC8800D80 module directory does not exist: %s\n' "$module_dir" >&2
    exit 4
fi

for module_name in "${expected_modules[@]}"; do
    module_path=
    for suffix in ko ko.xz ko.zst; do
        candidate="$module_dir/$module_name.$suffix"
        if [[ -f "$candidate" ]]; then
            module_path=$candidate
            break
        fi
    done

    if [[ -z "$module_path" ]]; then
        printf 'Missing %s for kernel %s.\n' "$module_name" "$kernel_release" >&2
        exit 4
    fi

    if ! package_owner=$(rpm -qf --qf '%{NAME}-%{VERSION}-%{RELEASE}.%{ARCH}' "$module_path" 2>&1); then
        package_owner='generated by akmods (not owned by an installed RPM)'
    elif [[ "$package_owner" != "kmod-aic8800d80-$kernel_release-"* ]]; then
        printf 'Unexpected owner for %s: %s\n' "$module_path" "$package_owner" >&2
        exit 4
    fi

    if ! vermagic=$(modinfo -F vermagic "$module_path" 2>&1); then
        printf 'Could not read vermagic from %s: %s\n' \
            "$module_path" "$vermagic" >&2
        exit 4
    fi
    if [[ ${vermagic%% *} != "$kernel_release" ]]; then
        printf 'Vermagic mismatch for %s: %s\n' "$module_path" "$vermagic" >&2
        exit 4
    fi

    printf '%s\n' "$module_name: $module_path ($package_owner; vermagic: $vermagic)"
done

printf 'Verified AIC8800D80 modules for kernel %s.\n' "$kernel_release"
